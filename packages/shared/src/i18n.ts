export function useI18n(owner: string) {
  const language = useSubscription(
    [appIds.subscriptions.preferencesSelectedLanguage],
    owner,
  );

  return useMemo(
    () => ({
      language,
      isRtl: language === "ar",
      t: (key: TranslationKey, params?: TranslationParams) =>
        translate(language, key, params),
    }),
    [language],
  );
}
