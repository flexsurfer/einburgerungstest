export const DEFAULT_LANGUAGE: AppLanguage = "en";

export function resolveLanguage(
  language: string | null | undefined,
): AppLanguage {
  const code = language?.trim().toLowerCase().split(/[-_]/)[0];
  return code === "de" ||
    code === "ru" ||
    code === "tr" ||
    code === "ar" ||
    code === "en"
    ? code
    : DEFAULT_LANGUAGE;
}

